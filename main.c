/**
3.1 Обработка двумерных массивов с небольшим количеством строк или столбцов
Составить программу для решения задачи с использованием двумерных
массивов.

24. Дан двумерный массив из 3 строк и 7 столбцов. Первый элемент каждого
столбца представляет длину наибольшей стороны, а две другие – стороны
одного из 7 треугольников, заданных столбцами исходного массива.
Напечатать номера столбцов, которыми заданы тупоугольные
треугольники, и количество таких столбцов. Считаем, что во всех случаях
треугольник существует.
*/
#include <stdio.h>
#include <malloc.h>
#include <locale.h>
#include <math.h>


int main()
{
    setlocale(0, "");
    setlocale(LC_NUMERIC, "C");

    printf("\n-----------------------------------------------------------------------------\n");
//ввод данных
    int n = 3, m;
    do{
        printf("\nВведите количество треугольников m: ");
        scanf("%d", &m);
        if (m < 1 || m >= 100){
            printf("\n=====================================================================\n\t\t");
            printf("Ошибка: нарушен диапазон входных данных");
            printf("\n=====================================================================\n");
        }
    }while (m < 1 || m >= 100);
    printf("-----------------------------------------------------------------------------\n");
    double **A;
    int i, j;
    A = (double**)malloc(n * sizeof(double*));
    for (i = 0; i < n; i++){
        A[i] = (double*)malloc(m * sizeof(double));
    }

    printf("\nВведите длин сторон треугольника:\n"
           "(через пробел): наибольшая_сторона сторона_2 сторона_3\n");
    for (j = 0; j < m; j++){
        printf("\nТреугольник №%d: ",j+1);
        scanf("%lf %lf %lf", &A[0][j], &A[1][j], &A[2][j]);
    }
    printf("\n-----------------------------------------------------------------------------\n");

    printf("\nВведено длин сторон треугольника:\n");
    printf(" _____");for (i = 0; i < m; i ++) printf(" _________");
    printf("\n| n\\m |");for (j = 0; j < m; j++) printf(" %4d    |",j+1);
    printf("\n -----");for (i = 0; i < m; i ++) printf("+---------");
    for (i = 0; i < n; i++){
        printf("\n| %3d |", i+1);
        for (j = 0; j < m; j++){
            printf(" %7.3f |", A[i][j]);
        }
    }
    printf("\n =====");for (i = 0; i < m; i ++) printf(" =========");


    printf("\n\n=============================================================================\n\n\t\t");
    int k = 0;
    printf("Результат:\n\n"
           "Тупоугольные треугольники заданы в столбцах: ");
    for (j = 0; j < m; j++){
        if (pow(A[0][j], 2) > pow(A[1][j], 2) + pow(A[2][j], 2)){
            printf("%d ", j+1);
            k += 1;
        }
    }
    if (k == 0) printf("нет");
    printf("\n\nКоличество тупоугольных треугольников: %d",k);
    printf("\n\n=============================================================================\n");

    for (i = 0; i < n; i++){
        free(A[i]);
    }
    free(A);
    return 0;
}
